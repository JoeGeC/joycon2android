package com.joegec.joycon2android.buttonmapping.target

/** A GameCube controller's own digital buttons and d-pad directions. */
enum class GameCubeButton(val displayName: String) {
    A("A"),
    B("B"),
    X("X"),
    Y("Y"),
    Z("Z"),
    Start("Start"),
    TriggerL("L"),
    TriggerR("R"),
    DPadUp("D-Pad Up"),
    DPadDown("D-Pad Down"),
    DPadLeft("D-Pad Left"),
    DPadRight("D-Pad Right"),
}

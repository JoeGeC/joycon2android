    A("A"),
    B("B"),
    X("X"),
    Y("Y"),
    L("L"),
    R("R"),
    ZL("ZL"),
    ZR("ZR"),
    Plus("+"),
    Minus("-"),
    Home("Home"),
    Capture("Capture"),
    LStickClick("L-Stick Click"),
    RStickClick("R-Stick Click"),
    DPadUp("D-Pad Up"),
    DPadDown("D-Pad Down"),
    DPadLeft("D-Pad Left"),
    DPadRight("D-Pad Right"),
}
